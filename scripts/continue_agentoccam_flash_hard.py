"""Fresh AgentOccam continuation after an explicit user pause; method unchanged."""
from datetime import datetime, timezone
import os
from pathlib import Path
import shutil
import subprocess

from scripts.run_agentoccam_flash_hard import ROOT, read, file_hash, check_hashes, verify, report
from web2kg.common.storage import write_json


def pause_selection(previous):
    p=read(previous/'protocol.json'); state=read(previous/'state.json')
    pause=read(previous/'user-pause.json',{})
    if state['status']!='user_stopped' or not pause.get('queue_and_workers_exited'):
        raise ValueError('Only a documented user pause can be continued')
    if pause.get('stop_sha256')!=file_hash(previous/'STOP'):
        raise ValueError('Pause STOP evidence changed')
    if p.get('inherited_tasks'):
        raise ValueError('Chained continuation requires explicit lineage handling')
    ids=p['task_ids']
    if len(ids)!=len(set(ids)) or set(state['tasks'])-set(map(str,ids)):
        raise ValueError('Invalid task schedule')
    inherited={}; statuses={}; pending=[]; interrupted=[]
    summary={r['task_id']:r for r in read(previous/'summary.json')['tasks']}
    for task in ids:
        folder=previous/str(task); row=state['tasks'].get(str(task))
        if row is None:
            if folder.exists(): raise ValueError('Unregistered task assets exist')
            pending.append(task); continue
        if row['status'] in {'completed','failed'}:
            if read(folder/'official.json',{}).get('score') not in (0,1):
                raise ValueError('Resolved task missing official score')
            if not (previous/f'trajectories/task-{task}.html').is_file():
                raise ValueError('Inherited trajectory missing')
            inherited[str(task)]=str(folder); statuses[str(task)]=row['status']; continue
        result=read(folder/'result.json',{})
        if (task!=pause.get('interrupted_task') or task!=state.get('current_task')
                or result.get('error')!='ResponsesError: User stop file present'):
            raise ValueError('Unresolved task was not cancelled by the user pause')
        interrupted.append({**summary[task], 'result_folder':str(folder),
            'trace':str(previous/f'trajectories/task-{task}.html'),
            'reason':'User pause; excluded from selected success rate, all usage retained'})
        pending.append(task)
    if len(interrupted)>1 or len(inherited)!=pause.get('completed_tasks'):
        raise ValueError('Pause selection does not match its receipt')
    return dict(inherited_tasks=inherited,inherited_statuses=statuses,
                run_task_ids=pending,interrupted_attempts=interrupted)


def retained_hashes(folder):
    """Do not traverse private auth junctions or generated bytecode."""
    result={}
    for directory,dirs,files in os.walk(folder):
        dirs[:]=[d for d in dirs if d not in {'auth','__pycache__'}]
        for name in files:
            if name.endswith('.pyc'): continue
            path=Path(directory)/name; result[str(path.resolve())]=file_hash(path)
    return result


def register_pause_continuation(batch, previous, checks):
    if batch.exists() or not batch.is_relative_to(ROOT/'runs'):
        raise ValueError('Use a fresh directory within runs')
    receipt=read(checks)
    if not receipt or not receipt.get('passed'): raise ValueError('Offline checks required')
    check_hashes(receipt['source_sha256'])
    old=verify(previous,full=True); selection=pause_selection(previous)
    if not selection['run_task_ids']: raise ValueError('No tasks remain')
    source=Path(old['runtime']); old_manifest=read(source/'manifest.json')
    runtime=batch/'frozen-runtime'; runtime.mkdir(parents=True)
    for name,sha in old_manifest.items():
        target=runtime/name
        if not target.resolve().is_relative_to(runtime): raise ValueError('Invalid manifest path')
        target.parent.mkdir(parents=True,exist_ok=True); shutil.copyfile(source/name,target)
    changes=['scripts/run_agentoccam_flash_hard.py','scripts/continue_agentoccam_flash_hard.py']
    for name in changes:
        shutil.copyfile(ROOT/name,runtime/name)
    manifest={name:file_hash(runtime/name) for name in sorted(set(old_manifest)|set(changes))}
    unchanged={name:sha for name,sha in old_manifest.items() if name not in changes}
    check_hashes({str(runtime/name):sha for name,sha in unchanged.items()})
    subprocess.run(['powershell.exe','-NoProfile','-Command',
        f"New-Item -ItemType Junction -Path '{runtime/'auth'}' -Target '{ROOT/'auth'}' | Out-Null"],
        check=True,capture_output=True,creationflags=subprocess.CREATE_NO_WINDOW)
    write_json(runtime/'manifest.json',manifest)
    shutil.copytree(previous/'upstream',batch/'upstream')
    for name in ('config.yml','public-inputs.json'):
        shutil.copyfile(previous/name,batch/name)
    p={**old,**selection,'version':'agentoccam-flash-hard42-user-continuation-v1',
       'created_at':datetime.now(timezone.utc).isoformat(),
       'authorization':'User explicitly resumed the paused experiment on 2026-11-11.',
       'runtime':str(runtime),'workspace':str(runtime),'stop_file':str(batch/'STOP'),
       'continuation':str(previous)}
    lineage=dict(previous=str(previous),reason='User pause/resume; no method repair or best-score selection',
        **selection,unchanged_method_files=len(unchanged),scheduler_changes=changes,
        previous_queue_seconds=read(previous/'state.json').get('seconds'),
        prior_repair_lineage=read(previous/'repair-lineage.json'))
    write_json(batch/'continuation.json',lineage); write_json(batch/'protocol.json',p)
    passport={**read(previous/'run_material_passport.json'),
        'source_manifest_sha256':file_hash(runtime/'manifest.json'),
        'prior_scores_inherited':True,'inherited_count':len(selection['inherited_tasks']),
        'new_starts':len(selection['run_task_ids']),'continuation':'continuation.json'}
    write_json(batch/'run_material_passport.json',passport)
    inputs=retained_hashes(batch/'upstream')
    for path in (batch/'config.yml',batch/'public-inputs.json',batch/'continuation.json',checks,
                 Path(p['credential_file']),ROOT/'auth/llm-crawl.env'):
        inputs[str(path)]=file_hash(path)
    write_json(batch/'runtime-inputs.json',inputs)
    protected={**read(previous/'protected-inputs.json'),**retained_hashes(previous),**inputs}
    write_json(batch/'protected-inputs.json',protected)
    names=['protocol.json','run_material_passport.json','runtime-inputs.json','protected-inputs.json','continuation.json','frozen-runtime/manifest.json']
    write_json(batch/'registration-integrity.json',{str(batch/name):file_hash(batch/name) for name in names})
    write_json(batch/'state.json',dict(status='registered',tasks={}))
    verify(batch,full=True); report(batch)
    print(dict(registered=str(batch),inherited=len(selection['inherited_tasks']),
               new_starts=len(selection['run_task_ids']),unchanged_sources=len(unchanged),protected=len(protected)))
